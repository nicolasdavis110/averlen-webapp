#!/usr/bin/env python3
"""Copy the iPhone app's subscription name lists into preview/subscription-patterns.js.

Coming up on the web must treat the same merchants as known bills as the
iPhone does, so the lists are copied, never retyped. Run after the lists in
RecurringDetector.swift change:

    python3 scripts/sync-subscription-patterns.py ../Candor/RecurringDetector.swift
"""
import json
import pathlib
import re
import sys


def string_list(source: str, function: str) -> list[str]:
    start = source.index(f"static func {function}() -> [String] {{")
    body = source[start:]
    body = body[body.index("[") : body.index("\n        ]")]
    return re.findall(r'^\s*"((?:[^"\\]|\\.)*)",?\s*(?://.*)?$', body, re.M)


def string_set(source: str, name: str) -> list[str]:
    start = source.index(f"static let {name}")
    # Ends at the line closing the list; an entry may itself contain "]".
    body = source[start : source.index("\n    ]", start)]
    return re.findall(r'"((?:[^"\\]|\\.)*)"', body)


def main() -> None:
    swift = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "../Candor/RecurringDetector.swift")
    source = swift.read_text()
    listed = string_list(source, "subscriptionPatterns")
    guaranteed = string_list(source, "guaranteedSubscriptionPatterns")
    everyday = string_set(source, "everydayWordBrands")
    endings = string_set(source, "brandEndings")
    if len(listed) < 300 or len(guaranteed) < 50 or len(everyday) < 30 or len(endings) < 20:
        sys.exit("Lists look too short; RecurringDetector.swift may have changed shape.")
    out = pathlib.Path(__file__).resolve().parent.parent / "preview" / "subscription-patterns.js"
    out.write_text(
        "// Generated by scripts/sync-subscription-patterns.py from the iPhone app's\n"
        "// RecurringDetector.swift. Do not edit by hand.\n"
        f"export const listedPatterns = {json.dumps(listed)};\n"
        f"export const guaranteedPatterns = {json.dumps(guaranteed)};\n"
        f"export const everydayWordBrands = {json.dumps(everyday)};\n"
        f"export const brandEndings = {json.dumps(endings)};\n"
    )
    print(f"{len(listed)} listed, {len(guaranteed)} guaranteed, {len(everyday)} everyday, {len(endings)} endings → {out}")


if __name__ == "__main__":
    main()
